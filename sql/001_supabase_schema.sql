insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
    ('pickbook-public', 'pickbook-public', true, 52428800, array['image/jpeg', 'image/png', 'image/webp']),
    ('pickbook-private', 'pickbook-private', false, 52428800, array[
        'application/pdf',
        'application/msword',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        'image/jpeg',
        'image/png'
    ])
on conflict (id) do update set
    public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists pickbook_public_storage_read on storage.objects;
create policy pickbook_public_storage_read on storage.objects
    for select
    using (bucket_id = 'pickbook-public');

drop policy if exists pickbook_service_storage_all on storage.objects;
create policy pickbook_service_storage_all on storage.objects
    for all
    using (auth.role() = 'service_role' and bucket_id in ('pickbook-public', 'pickbook-private'))
    with check (auth.role() = 'service_role' and bucket_id in ('pickbook-public', 'pickbook-private'));
