create extension if not exists pgcrypto;

create table if not exists public.books (
    id bigint generated by default as identity primary key,
    source text,
    title text,
    author text,
    genre text,
    cover text,
    download text,
    language text,
    synopsis text,
    chapters_count integer,
    chapter_content text,
    created_at timestamptz default now()
);

create table if not exists public.profiles (
    id text primary key,
    email text unique not null,
    password_hash text,
    email_verified integer not null default 0,
    email_verification_token text,
    email_verification_sent_at timestamptz,
    password_reset_token text,
    password_reset_sent_at timestamptz,
    username text unique,
    author_bio text,
    email_notifications_enabled integer not null default 1,
    author_notifications_enabled integer not null default 1,
    bank_name text,
    bank_account_name text,
    bank_account_number text,
    current_plan text not null default 'free',
    paystack_customer_id text,
    subscription_expiry timestamptz,
    referral_code text unique,
    referred_by text,
    referral_bonus_claimed_at timestamptz,
    signup_fingerprint text,
    terms_accepted_at timestamptz,
    terms_version text,
    streak_count integer not null default 0,
    last_read_date date,
    created_at timestamptz default now()
);

create table if not exists public.coupons (
    id bigint generated by default as identity primary key,
    code text unique not null,
    discount_type text not null,
    discount_value integer not null,
    plan_target text not null default 'standard',
    max_uses integer not null default 1,
    used_count integer not null default 0,
    expiry_date timestamptz,
    created_at timestamptz default now()
);

create table if not exists public.coupon_claims (
    id bigint generated by default as identity primary key,
    user_id text not null,
    coupon_id bigint not null,
    fingerprint text,
    claimed_at timestamptz default now(),
    constraint uq_coupon_claim_user_coupon unique (user_id, coupon_id),
    constraint fk_coupon_claim_profile foreign key (user_id) references public.profiles(id) on delete cascade,
    constraint fk_coupon_claim_coupon foreign key (coupon_id) references public.coupons(id) on delete cascade
);

create table if not exists public.paystack_events (
    id bigint generated by default as identity primary key,
    reference text unique not null,
    user_id text not null,
    plan text not null,
    amount integer not null,
    paystack_fee integer not null default 0,
    net_amount integer not null default 0,
    referral_code text,
    partner_code text,
    created_at timestamptz default now()
);

create table if not exists public.pending_payments (
    reference text primary key,
    kind text not null default 'subscription',
    user_id text,
    plan text,
    amount integer not null,
    metadata_json text,
    processed_at timestamptz,
    created_at timestamptz default now()
);

create table if not exists public.reading_activity (
    id bigint generated by default as identity primary key,
    user_id text not null,
    read_date date not null,
    chapters_read integer not null default 1,
    constraint uq_reading_activity_user_date unique (user_id, read_date)
);

create table if not exists public.stories (
    id bigint generated by default as identity primary key,
    author_id text references public.profiles(id) on delete set null,
    title text not null,
    slug text unique,
    genre text,
    cover text,
    synopsis text,
    status text not null default 'draft',
    review_feedback text,
    published_version_id bigint,
    scheduled_version_id bigint,
    created_at timestamptz default now(),
    updated_at timestamptz,
    reviewed_at timestamptz,
    published_at timestamptz,
    unpublished_at timestamptz
);

create table if not exists public.story_versions (
    id bigint generated by default as identity primary key,
    story_id bigint not null references public.stories(id) on delete cascade,
    version_number integer not null,
    title text not null,
    synopsis text,
    content text,
    status text not null default 'pending_review',
    submitted_at timestamptz,
    reviewed_at timestamptz,
    published_at timestamptz,
    scheduled_for timestamptz,
    created_at timestamptz default now(),
    constraint uq_story_version_number unique (story_id, version_number)
);

create table if not exists public.drafts (
    id bigint generated by default as identity primary key,
    story_id bigint not null references public.stories(id) on delete cascade,
    author_id text references public.profiles(id) on delete set null,
    title text not null,
    synopsis text,
    content text,
    manuscript_metadata_json text,
    created_at timestamptz default now(),
    updated_at timestamptz,
    constraint uq_draft_story_author unique (story_id, author_id)
);

create table if not exists public.reading_progress (
    id bigint generated by default as identity primary key,
    user_id text not null references public.profiles(id) on delete cascade,
    book_id bigint references public.books(id) on delete cascade,
    story_id bigint references public.stories(id) on delete cascade,
    chapter integer not null default 1,
    percent integer not null default 0,
    updated_at timestamptz default now(),
    constraint ck_reading_progress_one_content check (
        (book_id is not null and story_id is null)
        or
        (book_id is null and story_id is not null)
    )
);

create table if not exists public.bookmarks (
    id bigint generated by default as identity primary key,
    user_id text not null references public.profiles(id) on delete cascade,
    book_id bigint references public.books(id) on delete cascade,
    story_id bigint references public.stories(id) on delete cascade,
    chapter integer not null default 1,
    note text,
    created_at timestamptz default now(),
    constraint ck_bookmarks_one_content check (
        (book_id is not null and story_id is null)
        or
        (book_id is null and story_id is not null)
    )
);

create table if not exists public.user_library (
    id bigint generated by default as identity primary key,
    user_id text not null references public.profiles(id) on delete cascade,
    book_id bigint references public.books(id) on delete cascade,
    story_id bigint references public.stories(id) on delete cascade,
    status text not null default 'saved',
    created_at timestamptz default now(),
    constraint ck_user_library_one_content check (
        (book_id is not null and story_id is null)
        or
        (book_id is null and story_id is not null)
    )
);

create table if not exists public.downloads (
    id bigint generated by default as identity primary key,
    user_id text not null references public.profiles(id) on delete cascade,
    book_id bigint references public.books(id) on delete cascade,
    story_id bigint references public.stories(id) on delete cascade,
    device_id text,
    billing_cycle text,
    quota_consumed integer not null default 1,
    created_at timestamptz default now(),
    constraint ck_downloads_one_content check (
        (book_id is not null and story_id is null)
        or
        (book_id is null and story_id is not null)
    )
);

create table if not exists public.search_index (
    id bigint generated by default as identity primary key,
    content_type text not null,
    content_id bigint not null,
    title text not null,
    body text,
    created_at timestamptz default now(),
    updated_at timestamptz,
    constraint ck_search_index_content_type check (content_type in ('book', 'story')),
    constraint uq_search_index_content unique (content_type, content_id)
);

create table if not exists public.reader_engagement (
    id bigint generated by default as identity primary key,
    user_id text not null references public.profiles(id) on delete cascade,
    book_id bigint references public.books(id) on delete cascade,
    story_id bigint references public.stories(id) on delete cascade,
    rating integer,
    liked integer not null default 0,
    comment text,
    comment_status text not null default 'pending_review',
    report_count integer not null default 0,
    report_reason text,
    moderation_note text,
    edited_at timestamptz,
    created_at timestamptz default now(),
    updated_at timestamptz,
    constraint ck_reader_engagement_one_content check (
        (book_id is not null and story_id is null)
        or
        (book_id is null and story_id is not null)
    ),
    constraint uq_reader_engagement_user_book unique (user_id, book_id),
    constraint uq_reader_engagement_user_story unique (user_id, story_id)
);

create table if not exists public.story_review_audits (
    id bigint generated by default as identity primary key,
    story_id bigint not null references public.stories(id) on delete cascade,
    admin_id text,
    action text not null,
    from_status text,
    to_status text,
    note text,
    created_at timestamptz default now()
);

create table if not exists public.author_notifications (
    id bigint generated by default as identity primary key,
    author_id text not null references public.profiles(id) on delete cascade,
    story_id bigint references public.stories(id) on delete set null,
    kind text not null,
    title text not null,
    message text,
    read_at timestamptz,
    created_at timestamptz default now()
);

create table if not exists public.author_earnings (
    id bigint generated by default as identity primary key,
    author_id text not null references public.profiles(id) on delete cascade,
    story_id bigint references public.stories(id) on delete set null,
    source text not null default 'manual',
    amount_kobo integer not null default 0,
    status text not null default 'available',
